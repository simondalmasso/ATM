import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const src=path.join(here,'ATM-ORDER034-ACTIVE-MAIN-READONLY.js');
const tmp=path.join(os.tmpdir(),`atm-status-truth-${process.pid}-${Date.now()}.mjs`);
let code=fs.readFileSync(src,'utf8').replace('import { DurableObject } from "cloudflare:workers";','class DurableObject { constructor(ctx,env){} }');
code+='\nexport { selectCurrentRuntime, reconcileAgenticRuntimeTruth, reconcileWatchdogRuntimeTruth };\n';
fs.writeFileSync(tmp,code,'utf8'); process.on('exit',()=>{try{fs.unlinkSync(tmp)}catch{}});
const mod=await import(pathToFileURL(tmp).href+'?v='+Date.now());
const stale={job_id:'old-job',task_id:'old-task',source:'DAYDREAMS',stage:'ABORTED',terminal:true,selected_at:'2026-09-16T20:00:00Z'};
const idle={status:'IDLE_NO_AUTO_ELIGIBLE_TASK',execution_job_id:null,selected_task_id:null,dispatch_id:null};
if(mod.selectCurrentRuntime(idle,{old:stale})!==null) throw new Error('IDLE_SELECTED_STALE_RUNTIME');
const idleTruth=mod.reconcileAgenticRuntimeTruth(idle,{old:stale});
if(idleTruth.status!=='IDLE_NO_AUTO_ELIGIBLE_TASK'||idleTruth.execution_job_id) throw new Error('IDLE_TRUTH_OVERRIDDEN:'+JSON.stringify(idleTruth));
const staleWatchdog={classification:'STALLED',anomaly:'A5_VERIFIER_FAILED_WITH_ARTIFACT',recommended_action:'RETRY',task_id:'old-task'};
const idleWatchdog=mod.reconcileWatchdogRuntimeTruth(idle,{old:stale},staleWatchdog);
if(idleWatchdog.classification!=='HEALTHY'||idleWatchdog.anomaly!=='NONE'||idleWatchdog.active_runtime!==false) throw new Error('IDLE_WATCHDOG_STALE:'+JSON.stringify(idleWatchdog));
const active={status:'EXECUTING',execution_job_id:'hansa-job',selected_task_id:'hansa-task',dispatch_id:'d1'};
const hansa={job_id:'hansa-job',task_id:'hansa-task',source:'AGENTHANSA',stage:'VERIFYING',terminal:false,dispatch_id:'d1'};
const activeTruth=mod.reconcileAgenticRuntimeTruth(active,{h:hansa,old:stale});
if(activeTruth.status!=='VERIFYING'||activeTruth.execution_job_id!=='hansa-job'||activeTruth.canonical_task_runtime!==true) throw new Error('ACTIVE_RUNTIME_NOT_RECONCILED:'+JSON.stringify(activeTruth));
console.log('IDLE_IGNORES_STALE_RUNTIME=PASS');
console.log('ACTIVE_CURRENT_JOB_RECONCILES=PASS');
console.log('IDLE_WATCHDOG_CLEARS_STALE_ANOMALY=PASS');
console.log('GENERIC_SOURCE_RECONCILIATION=PASS');
console.log('PRODUCTION_MUTATION=0');