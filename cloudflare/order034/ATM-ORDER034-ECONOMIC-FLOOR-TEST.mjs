import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const src=path.join(here,'ATM-ORDER034-ACTIVE-MAIN-READONLY.js');
const tmp=path.join(os.tmpdir(),`atm-order034-economic-floor-${process.pid}-${Date.now()}.mjs`);
let code=fs.readFileSync(src,'utf8').replace('import { DurableObject } from "cloudflare:workers";','class DurableObject { constructor(ctx,env){} }');
code+='\nexport { normalize, detectBlockers, MIN_PRIMARY_REWARD_USD };\n';
fs.writeFileSync(tmp,code,'utf8');
process.on('exit',()=>{try{fs.unlinkSync(tmp)}catch{}});
const mod=await import(pathToFileURL(tmp).href+'?v='+Date.now());
if(mod.MIN_PRIMARY_REWARD_USD!==100) throw new Error(`MIN_PRIMARY_REWARD_USD_EXPECTED_100:${mod.MIN_PRIMARY_REWARD_USD}`);
const raw=(netReward)=>({id:'task-'+netReward,description:'Write a concise plain-text report.',netReward:String(netReward),reward:String(netReward),status:'open',mode:'bounty',stakeRequired:false,stakeBps:0,submissionWindowOpen:true,pendingActions:[{role:'worker',action:'submit',requiresPayment:false,paymentAmount:null}]});
const low=mod.normalize('DAYDREAMS',raw(1_000_000));
if(!low.blockers.includes('BELOW_MIN_REWARD_USD')) throw new Error('LOW_REWARD_NOT_BLOCKED:'+JSON.stringify(low.blockers));
if(low.ai_executability!=='BLOCKED') throw new Error('LOW_REWARD_AI_EXECUTABLE');
const floor=mod.normalize('DAYDREAMS',raw(100_000_000));
if(floor.blockers.includes('BELOW_MIN_REWARD_USD')) throw new Error('FLOOR_REWARD_BLOCKED');
const unsafe=mod.detectBlockers({source:'XGODO',title:'Create a Google account',description:'Create a Google account automatically and return the account email and password.',raw:{}});
if(!unsafe.includes('ACCOUNT_FARMING_OR_BULK_ACCOUNT_CREATION')) throw new Error('XGODO_GOOGLE_ACCOUNT_NOT_SAFETY_BLOCKED:'+JSON.stringify(unsafe));
console.log('MIN_PRIMARY_REWARD_USD=100');
console.log('LOW_REWARD_BLOCKED=PASS');
console.log('FLOOR_REWARD_ADMITTED=PASS');
console.log('XGODO_GOOGLE_ACCOUNT_REJECTED=PASS');
console.log('PRODUCTION_MUTATION=0');
